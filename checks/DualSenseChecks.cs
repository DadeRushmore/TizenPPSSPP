using System;
using System.Collections.Generic;
using System.Collections.Concurrent;
using System.Threading;

internal static class DualSenseChecks
{
    static void Need(bool ok,string why){if(!ok)throw new Exception("DualSense: "+why);}
    static byte[] Simple(byte faces){var p=new byte[10];p[0]=1;p[5]=(byte)(8|faces);return p;}
    static uint Decode(byte[] p,int bus=5){uint bits;string kind;Need(DualSenseReports.Decode(p,p.Length,bus,out bits,out kind),"valid report "+p.Length);return bits;}
    static void Until(Func<bool> predicate,string why){double end=ControllerReader.Now+3;while(ControllerReader.Now<end){if(predicate())return;Thread.Sleep(5);}Need(false,why);}
    sealed class FakeHid : IDualSenseHid {
        internal readonly ConcurrentQueue<byte[]> Packets=new ConcurrentQueue<byte[]>();
        internal int Opened,Closed;
        internal volatile bool Disconnect;
        public int OpenSingle(out int bus,out string detail){bus=5;detail="mock DualSense";Interlocked.Increment(ref Opened);return 7;}
        public int Read(int fd,byte[] buffer,out int error){if(Disconnect){error=19;return -1;}byte[] p;if(Packets.TryDequeue(out p)){Array.Copy(p,buffer,p.Length);error=0;return p.Length;}error=11;return -1;}
        public void Close(int fd){Need(fd==7,"fd ownership");Interlocked.Increment(ref Closed);}
    }
    internal static void Run() {
        const uint c=DualSenseReports.Circle,t=DualSenseReports.Triangle;
        Need(Decode(Simple(0))==0&&Decode(Simple(0x40))==c&&Decode(Simple(0x80))==t&&Decode(Simple(0xc0))==(c|t),"independent and simultaneous Bluetooth simple buttons");
        var padded=new byte[78];Array.Copy(Simple(0x40),padded,10);Need(Decode(padded)==c,"padded Bluetooth simple");
        var usb=new byte[64];usb[0]=1;usb[5]=0xc8;usb[8]=0x88;Need(Decode(usb,3)==t,"USB offsets must not use simple layout");
        var full=new byte[78];full[0]=0x31;full[9]=0xc8;
        // Independently generated by Python zlib.crc32(0xA1 + first 74 bytes).
        full[74]=0x34;full[75]=0xcc;full[76]=0xdb;full[77]=0x3f;
        Need(Decode(full)==(c|t),"Bluetooth full CRC and offset");
        uint ignored;string format;full[9]^=0x40;
        Need(!DualSenseReports.Decode(full,78,5,out ignored,out format),"bad CRC accepted");
        Need(!DualSenseReports.Decode(usb,64,5,out ignored,out format),"wrong transport layout accepted");
        Need(!DualSenseReports.Decode(Simple(0),9,5,out ignored,out format)&&!DualSenseReports.Decode(Simple(0),129,5,out ignored,out format),"truncated/oversize report accepted");
        var wrong=Simple(0);wrong[0]=0x11;Need(!DualSenseReports.Decode(wrong,10,5,out ignored,out format),"DS4 report accepted");
        wrong=Simple(0);wrong[5]=0xcf;Need(!DualSenseReports.Decode(wrong,10,5,out ignored,out format),"invalid hat/report accepted");

        var map=new PspInputMap();map.Assign(0,"button:1");map.Assign(1,"button:13");map.Assign(3,"button:2");map.Assign(4,"button:4");
        string saved=map.Serialize();var state=new DualSenseFaceState();
        map.ObserveRaw(1,2,1);Need(state.Merge(map)==t,"original fallback");
        state.Apply(true,c);Need(state.Merge(map)==0,"activation needs a neutral report and suppresses collided source");
        state.Apply(true,0);state.Apply(true,c);Need(state.Merge(map)==c,"Circle must not also send Triangle");
        map.ObserveRaw(1,1,1);map.ObserveRaw(1,4,1);map.ObserveRaw(1,13,1);
        state.Apply(true,t);Need(state.Merge(map)==(c|t|1u|(1u<<10)),"R3/Cross/shoulder retained");
        state.Apply(true,0);Need((state.Merge(map)&c)!=0,"physical R3 survives direct Circle release");
        state.Apply(true,c|t);state.BlockHeld();Need(state.Gameplay==0,"UI transition consumes held faces");
        state.Apply(true,c);Need(state.Gameplay==0,"partial release must not reactivate");state.Apply(true,0);state.Apply(true,t);Need(state.Gameplay==t,"release re-arms");
        state.Apply(true,0);state.BlockUntilNeutral();state.Apply(true,c);Need(state.Gameplay==0,"queued old press after UI change must wait for neutral snapshot");state.Apply(true,0);state.Apply(true,c);Need(state.Gameplay==c,"fresh post-menu press");
        state.Apply(false,0);Need(state.Gameplay==0&&map.Serialize()==saved,"disconnect clears direct state without overwriting bindings");

        var nav=new ControllerNavigation();nav.Observe(map,1,2,1);nav.ObserveFaces(true,c);
        Need(nav.Next(1,true,false,ControllerNavigation.Directions)=="XF86Back","real Circle backs out of menu");
        nav.BlockHeld();Need(nav.Next(2,true,false,ControllerNavigation.Directions)==null,"held direct Circle reactivated menu");
        nav.Observe(map,1,2,0);nav.ObserveFaces(true,0);nav.Next(3,true,false,ControllerNavigation.Directions);
        nav.Observe(map,1,2,1);nav.ObserveFaces(true,t);Need(nav.Next(4,true,false,ControllerNavigation.Directions)==null,"Triangle must not navigate Back");
        nav.Observe(map,1,13,1);Need(nav.Next(5,true,false,ControllerNavigation.Directions)=="XF86Back","R3 menu fallback");

        var io=new FakeHid();var reader=new DualSenseHidReader(io);var events=new List<DualSenseHidReader.State>();reader.Start();
        try {
            reader.Allowed=true;io.Packets.Enqueue(Simple(0));io.Packets.Enqueue(Simple(0x40));io.Packets.Enqueue(Simple(0));
            Until(()=>{events.AddRange(reader.Drain());return events.Count>=3;},"short tap transitions lost");
            Need(events[0].Active&&events[0].Faces==0&&events[1].Faces==c&&events[2].Faces==0,"ordered tap/neutral snapshots");
            reader.Resync();var fresh=reader.Drain();Need(fresh.Length==1&&fresh[0].Active&&fresh[0].Faces==0,"menu resync loses current neutral state");
            for(int i=0;i<700;i++)io.Packets.Enqueue(Simple(i%2==0?(byte)0x40:(byte)0));
            Until(()=>reader.Diagnostics.Contains("queue_overflows=2"),"face transition queue was not bounded");
            var overflow=reader.Drain();Need(overflow.Length<=256&&Array.Exists(overflow,e=>!e.Active),"overflow must clear/re-arm delivery");
            io.Packets.Enqueue(Simple(0x80));Until(()=>reader.Diagnostics.Contains("faces=512"),"held Triangle not received");reader.Drain();
            io.Disconnect=true;Until(()=>io.Closed>0,"disconnect fd not closed");
            // Close and route invalidation are consecutive worker actions, not one atomic event.
            Until(()=>Array.Exists(reader.Drain(),e=>!e.Active),"disconnect did not release route");
            reader.Allowed=false;io.Disconnect=false;Thread.Sleep(20);
            reader.Allowed=true;io.Packets.Enqueue(Simple(0));Until(()=>reader.Diagnostics.Contains("active=True"),"reconnect did not recover");reader.Drain();
            Until(()=>Array.Exists(reader.Drain(),e=>!e.Active),"stale stream did not release within timeout");
            reader.Allowed=false;Need(!Array.Exists(reader.Drain(),e=>e.Active),"disabled reader retained active input");
        }finally{reader.Stop();Until(()=>reader.Finished,"worker did not stop");}
        Need(io.Opened==io.Closed,"leaked descriptor");
        var check=new ButtonIdentityCheck(0);
        for(int i=0;i<6;i++){double when=i*6+2;check.Raw(1,2,1,when);check.Faces(true,i%2==0?c:t,when);check.Raw(1,2,0,when+.5);check.Faces(true,0,when+.5);}
        check.Tick(36);Need(check.Result.StartsWith("Repeatable distinct")&&check.Report.Contains("hid:Circle:8")&&check.Report.Contains("hid:Triangle:9"),"HID identity evidence absent");
        Console.WriteLine("PASS: DualSense simple/padded/full/USB reports, CRC, independent faces, collision masking, R3/stick-map preservation, menu release gating, tap ordering, disconnect/reconnect/stale cleanup and fd ownership");
    }
}
